"""Write docs/QUALITY_REPORT.md: a readable summary of the checks of the latest run."""
from __future__ import annotations

from .config import ROOT

WHAT = {
    "QC01": "Every month from 2018-01 to the latest month exists for every material",
    "QC02": "No partner flow has a value without a quantity",
    "QC03": "Unit value within 3.5 robust z-scores (median / MAD) and 25% of its 13-month median",
    "QC04": "Monthly quantity above 10% of the material's median quantity",
    "QC05": "Unit value level across a customs-code change",
    "QC06": "CN8 codes used only inside their validity window",
    "QC07": "No duplicate keys",
    "QC08": "kg and m3 consistent for gases",
    "QC09": "Partner country disclosed for at least 90% of the value",
    "QC10": "USGS reference values present (not withheld)",
    "QC11": "Each source as fresh as its normal publication lag",
    "QC12": "An ECB exchange rate exists for every month",
    "QC13": "Comtrade quantities reported, not estimated",
    "QC14": "Partner unit value inside the plausible range of the material (else excluded)",
}


def write(con) -> None:
    summ = con.sql("SELECT * FROM quality_summary").df().set_index("check_id")
    fresh = con.sql("SELECT source, strftime(latest_period, '%Y-%m') AS latest, collected_on, lag_months, expected_max_lag FROM freshness ORDER BY source").df()
    excl = con.sql("""SELECT material_id,
                         round(100 * sum(quantity_kg) FILTER (WHERE quantity_kg > 0 AND (uv < lo OR uv > hi)) / sum(quantity_kg), 1) AS pct_kg_excluded,
                         round(100 * sum(value_eur) FILTER (WHERE quantity_kg > 0 AND (uv < lo OR uv > hi)) / sum(value_eur), 1) AS pct_value_excluded
                      FROM partner_rows WHERE flow = 'import' GROUP BY 1 ORDER BY 2 DESC, 1""").df()
    top = con.sql("""SELECT check_id, material_id, strftime(period, '%Y-%m') AS period, detail FROM quality_checks
                     WHERE check_id IN ('QC01', 'QC03', 'QC05', 'QC08') ORDER BY check_id, abs(value) DESC NULLS LAST LIMIT 25""").df()
    L = ["# Data quality report", "", "Generated by `python -m pipeline run`. Rules: `sql/03_checks.sql`. What to do when a check fails: `docs/RUNBOOK.md`.", "",
         "| Check | Rule | Severity | Rows flagged | Materials |", "|---|---|---|---|---|"]
    for cid, rule in WHAT.items():
        if cid in summ.index:
            r = summ.loc[cid]
            L.append(f"| {cid} | {rule} | {r.severity} | {int(r.rows_flagged):,} | {int(r.materials_affected)} |")
        else:
            L.append(f"| {cid} | {rule} | pass | 0 | 0 |")
    L += ["", "## Freshness", "", "| Source | Latest period | Collected on | Lag (months) | Normal lag |", "|---|---|---|---|---|"]
    L += [f"| {r.source} | {r.latest} | {r.collected_on} | {r.lag_months} | <= {r.expected_max_lag} |" for r in fresh.itertuples()]
    L += ["", "## Share of EU imports excluded by the plausibility check (QC14)", "", "| Material | % of kg | % of value |", "|---|---|---|"]
    L += [f"| {r.material_id} | {r.pct_kg_excluded} | {r.pct_value_excluded} |" for r in excl.itertuples()]
    L += ["", "## Largest flags", "", "| Check | Material | Period | Detail |", "|---|---|---|---|"]
    L += [f"| {r.check_id} | {r.material_id} | {r.period} | {r.detail} |" for r in top.itertuples()]
    (ROOT / "docs" / "QUALITY_REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("  docs/QUALITY_REPORT.md written")
